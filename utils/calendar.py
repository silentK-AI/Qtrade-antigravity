    @classmethod
    def is_trading_day(cls, dt: Optional[datetime] = None) -> bool:
        """
        判断指定日期是否为 A 股真实交易日：
        1. 必须是周一至周五 (0 <= weekday < 5)；
        2. 不能是法定节假日休市日。
        """
        if dt is None:
            dt = get_beijing_now()

        # 1. 周末必休 (A 股周末无交易，即使国家假日调休补班，股市亦休市)
        if dt.weekday() >= 5:
            return False

        # 2. 检查法定节假日休市表
        date_str = dt.strftime("%Y-%m-%d")
        if date_str in cls.MARKET_HOLIDAYS:
            return False

        return True
