#!/bin/bash
# ==============================================================================
# 在服务器端执行：从 GitHub / Gitee 拉取最新代码并一键热重启
# ==============================================================================

set -e

APP_DIR="$(cd "$(dirname "$0")/.." && pwd)"
cd "$APP_DIR"

echo "=================================================================="
echo "  1. 正在从远程仓库拉取最新打板量化代码 (git pull)..."
echo "=================================================================="
git pull

echo "=================================================================="
echo "  2. 停用并清理老量化进程..."
echo "=================================================================="
pkill -f "stock_scheduler" 2>/dev/null || true
pkill -f "stock_alert_monitor" 2>/dev/null || true
pkill -f "main.py" 2>/dev/null || true

echo "=================================================================="
echo "  3. 启动全新【A股打板量化系统】守护服务 (开机自启)..."
echo "=================================================================="
cp deploy/quant-screener.service /etc/systemd/system/
systemctl daemon-reload
systemctl enable quant-screener
systemctl restart quant-screener

echo "=================================================================="
echo "  更新部署成功！当前运行状态："
systemctl status quant-screener --no-pager
echo "=================================================================="
